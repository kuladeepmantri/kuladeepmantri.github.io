#!/usr/bin/env tsx
/**
 * Build-time GitHub data fetcher.
 *
 * Runs as `prebuild` (npm lifecycle). Reads all unique repos referenced by
 * `app/signals.ts`, queries GitHub GraphQL in one batched call via field
 * aliases, and writes the result to `lib/generated/github.ts` so
 * `@/lib/github` can import it synchronously at compile time.
 *
 * Design notes:
 *   - Zero runtime deps: uses native fetch (Node 18+). No Octokit chain.
 *   - Never throws. A missing token, a failed fetch, or a private repo all
 *     degrade to an empty entry with `error: true`. The site always builds.
 *   - If `lib/generated/github.ts` already exists (last good run) and the
 *     current fetch fails, the old file is preserved (stale-cache fallback).
 *
 * Never commit the generated file. It's in .gitignore.
 */
import { writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

import { SIGNALS } from '../app/signals'

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUT_FILE = join(__dirname, '..', 'lib', 'generated', 'github.ts')
const TOKEN = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN ?? ''

// ── Types (mirrored in lib/github.ts consumer) ──

interface RepoCommit {
  sha: string
  message: string
  date: string
}

interface RepoData {
  repo: string
  commits7d: number
  commits30d: number
  openPRs: number
  recentCommits: RepoCommit[]
  fetchedAt: string
  error: boolean
}

// ── Helpers ──

function emptyRepoData(repo: string, error: boolean): RepoData {
  return {
    repo,
    commits7d: 0,
    commits30d: 0,
    openPRs: 0,
    recentCommits: [],
    fetchedAt: new Date().toISOString(),
    error,
  }
}

function writeModule(data: Record<string, RepoData>): void {
  mkdirSync(dirname(OUT_FILE), { recursive: true })

  const header = `// AUTO-GENERATED by scripts/fetch-github.ts. Do not edit by hand.
// Regenerated on every \`npm run build\` when GITHUB_TOKEN / GH_TOKEN is set.

export interface RepoCommit {
  sha: string
  message: string
  date: string
}

export interface RepoData {
  repo: string
  commits7d: number
  commits30d: number
  openPRs: number
  recentCommits: RepoCommit[]
  fetchedAt: string
  error: boolean
}

export const GITHUB_DATA: Record<string, RepoData> = ${JSON.stringify(data, null, 2)}
`

  writeFileSync(OUT_FILE, header, 'utf8')
}

// ── Main ──

async function main(): Promise<void> {
  const repos = Array.from(new Set(SIGNALS.flatMap((s) => s.repos))).filter(Boolean)

  if (repos.length === 0) {
    console.log('[fetch-github] no repos referenced by any signal — writing empty module')
    writeModule({})
    return
  }

  if (!TOKEN) {
    console.warn('[fetch-github] no GITHUB_TOKEN / GH_TOKEN — writing stub module')
    const stub: Record<string, RepoData> = {}
    for (const repo of repos) stub[repo] = emptyRepoData(repo, true)
    writeModule(stub)
    return
  }

  const now = new Date()
  const cutoff7d = new Date(now.getTime() - 7 * 24 * 60 * 60 * 1000)
  const cutoff30d = new Date(now.getTime() - 30 * 24 * 60 * 60 * 1000)

  // Build one batched GraphQL query using aliases. Repo slugs contain a slash,
  // which is not a valid GraphQL alias character — so we index-alias them.
  const aliases = repos
    .map((repo, i) => {
      const [owner, name] = repo.split('/')
      return `r${i}: repository(owner: "${owner}", name: "${name}") {
        defaultBranchRef {
          target {
            ... on Commit {
              history(first: 100) {
                nodes { oid messageHeadline committedDate }
              }
            }
          }
        }
        pullRequests(states: OPEN) { totalCount }
      }`
    })
    .join('\n')

  const query = `{ ${aliases} }`

  try {
    const res = await fetch('https://api.github.com/graphql', {
      method: 'POST',
      headers: {
        Authorization: `bearer ${TOKEN}`,
        'Content-Type': 'application/json',
        'User-Agent': 'kuladeepmantri-site-build',
      },
      body: JSON.stringify({ query }),
    })

    if (!res.ok) {
      throw new Error(`GitHub GraphQL ${res.status}: ${await res.text()}`)
    }

    const json = (await res.json()) as {
      data?: Record<string, null | {
        defaultBranchRef: null | { target: null | { history: { nodes: Array<{ oid: string; messageHeadline: string; committedDate: string }> } } }
        pullRequests: { totalCount: number }
      }>
      errors?: Array<{ message: string }>
    }

    if (!json.data) {
      throw new Error(`GitHub response missing data: ${JSON.stringify(json.errors ?? json)}`)
    }

    const out: Record<string, RepoData> = {}

    for (let i = 0; i < repos.length; i++) {
      const repo = repos[i]
      const node = json.data[`r${i}`]
      if (!node) {
        out[repo] = emptyRepoData(repo, true)
        continue
      }
      const history = node.defaultBranchRef?.target?.history?.nodes ?? []
      const commits7d = history.filter(
        (c) => new Date(c.committedDate) >= cutoff7d,
      ).length
      const commits30d = history.filter(
        (c) => new Date(c.committedDate) >= cutoff30d,
      ).length
      const recentCommits = history.slice(0, 10).map((c) => ({
        sha: c.oid.slice(0, 7),
        message: c.messageHeadline,
        date: c.committedDate,
      }))
      out[repo] = {
        repo,
        commits7d,
        commits30d,
        openPRs: node.pullRequests.totalCount,
        recentCommits,
        fetchedAt: now.toISOString(),
        error: false,
      }
    }

    writeModule(out)
    console.log(
      `[fetch-github] wrote ${Object.keys(out).length} repo entries to ${OUT_FILE}`,
    )
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err)
    console.error('[fetch-github] fetch failed:', msg)
    if (existsSync(OUT_FILE)) {
      console.log('[fetch-github] retaining prior generated file as stale cache')
      return
    }
    console.log('[fetch-github] no prior cache — writing stub module')
    const stub: Record<string, RepoData> = {}
    for (const repo of repos) stub[repo] = emptyRepoData(repo, true)
    writeModule(stub)
  }
}

main().catch((err) => {
  // Absolute last-resort: never let the build fail because of this script.
  console.error('[fetch-github] fatal:', err)
  process.exit(0)
})
